#!/usr/bin/env python3
"""APG-M10: writes the prototype's data file, ui/data/views.js, from the existing APG code run on Builder Zero (apg_ui.viewmodel).  Synthetic data only; nothing leaves this
machine.  The file is generated, never edited by hand: --check regenerates it in memory and fails if the stored file differs by one byte.
Usage: python3 -I tools/build_m10_views.py [--check]"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.dont_write_bytecode = True
from apg_ui import viewmodel as VM            # noqa: E402

OUT = os.path.join(ROOT, 'ui', 'data', 'views.js')
HEAD = ('// Generated by tools/build_m10_views.py from the APG code run on synthetic Builder Zero data. Do not edit.\n'
        '// Prototype data only: not an API response, not a production screen.\n')


def wrap(json_text):
    return HEAD + 'window.APG_VIEWS = ' + json_text.rstrip('\n') + ';\n'


def render():
    return wrap(VM.dumps(VM.build_views(ROOT)))


def main():
    text = render()
    if '--check' in sys.argv[1:]:
        same = os.path.exists(OUT) and open(OUT, encoding='utf-8').read() == text
        print('views.js %s (%d bytes)' % ('matches a fresh build' if same else 'DIFFERS from a fresh build', len(text)))
        return 0 if same else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d bytes)' % (os.path.relpath(OUT, ROOT), len(text)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
