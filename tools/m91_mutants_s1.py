#!/usr/bin/env python3
"""APG-M11-S1 successor of tools/m91_mutants.py (P5-S08, P5-S07, P5-B06; DP-1.2 (B): tools/m91_mutants.py stays byte-identical).
The mutants are M10's own, unchanged: the same targets, kinds, traversal order and ids, generated by M10's candidates() and mutate(),
which this tool loads from tools/m91_mutants.py; the documented equivalents are M10's EQUIV.  What changes is how they are run and judged
(R1_REQUIREMENTS.md §2; tools/evkit.mutation_main): a pinned universe and site hashes, a preflight before any mutant, start and end
controls on the same unparse round trip, each mutant in its own fresh copy, the kill oracle tools/mut_runner_s1.py (mode=failfast, its
first failing file in M10's order), a timeout or a crash never a kill (DP-2.1 (a)), and kind=mutation evidence with one RESULT v=3 line.
Usage (from the package root):  python3 -I -S tools/m91_mutants_s1.py [--list] [--jobs N] [--only PREFIX] [--ids A,B] [--run-id ID]
                                 python3 -I -S tools/m91_mutants_s1.py --pin --reason TEXT --cause TEXT
Exit codes as §2.4.  The M10 success marker 'MUTATION RUN OK' is printed only on exit 0.     BUILDER-EXECUTED: NOT INDEPENDENT."""
import os
import sys

sys.dont_write_bytecode = True
ROOT = os.path.realpath(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)
import tools.evkit as E  # noqa: E402

TOOL = 'm91_mutants_s1'
M = None   # moved into load() under evkit.import_guard (corrective pass 2, C.1)
PKG = 'apg/api'

def load():
    """C.1: the M10 load, and every module-level statement that uses it, after the start checks (evkit.guarded_load)."""
    global M
    with E.import_guard('m91_mutants'):
        M = E.load_tool_module('m91_mutants', ROOT)


def mutants():
    out = []
    srcs = {}
    for mid, mod, kind, idx in M.candidates():
        rel = '%s/%s.py' % (PKG, mod)
        if rel not in srcs:
            with open(os.path.join(ROOT, rel), encoding='utf-8') as fh:
                srcs[rel] = fh.read()
        out.append(E.Mutant(mid, rel, E.ast_site(srcs[rel], M._sites, kind, idx),
                            (lambda src, kind=kind, idx=idx: M.mutate(src, kind, idx)), group=mod))
    return out


def commands(work, mutant):
    mod = mutant.group if mutant is not None else M.TARGETS[0][1]
    order = [M.FIRST[mod]] + [t for t in M.ALL_TESTS if t != M.FIRST[mod]]
    return [('mut_runner_s1', E.child_cmd(os.path.join(work, 'tools', 'mut_runner_s1.py'),
                                          ['--caller', 'mutation_tool', '--run-id', (mutant.id if mutant else 'control')] + order))]


def main(argv):
    ms, rc = E.list_mutants(TOOL, mutants)   # decision (c) (owner, 2026-11-02 14:24): a failed listing is a refusal, not a crash
    if rc is not None:
        return rc
    targets = sorted({m.relpath for m in ms})
    return E.mutation_main(TOOL, ms, commands, argv, equivalents=M.EQUIV, baseline=E.unparse_baseline(targets), timeout=300,
                           success_marker='MUTATION RUN OK')


if __name__ == '__main__':
    rc = E.guarded_load(TOOL, 'mutation', load)
    if rc is not None:
        sys.exit(rc)
    sys.exit(main(sys.argv[1:]))
