"""The M3 fault corpus (apg/ingest/corpus.py, 44 deliberately faulty files on the AP-invoice layout) sent through AUIF's own file importer and the APG module, compared with
the M3 path case by case.  The expected outcome of every case is declared in auif_m8/PATH_EQUIVALENCE_DECLARED_DIFFERENCES.json ('same', 'refused_on_both_paths', 'differs'),
written before this test existed.  The pack used here is generated by the same generator from the GOOD corpus layout; the faulty file never chooses its own pack."""
import json, os, shutil, tempfile, unittest
from dataclasses import replace
from ._auif import HERE_ROOT, D, PK, client, codes, comparable, gate, records, world
from apg.ingest import corpus as CORPUS, mapping, pipeline as P
from apg.ports import TenantMismatch

DECL = json.load(open(os.path.join(HERE_ROOT, 'auif_m8', 'PATH_EQUIVALENCE_DECLARED_DIFFERENCES.json'), encoding='utf-8'))['corpus']
CASES = {c['id']: c for c in CORPUS.cases()}
TPL = next(t for t, *_ in D.files_for(HERE_ROOT, 'zero_one') if t['template_id'] == 'TPL-BZ-AP-INVOICES')
IID = 'corpus-accounting'


def _config():
    """The stored configuration plus one pack for an integration that holds only ap_invoices.csv, laid out as the GOOD corpus file."""
    cfg = client.load_config(HERE_ROOT)
    from apg_auif import definitions as DEF
    from auif_ext.connectors.file_import import FileImportConnector, FileSpec
    d = tempfile.mkdtemp()
    try:
        open(os.path.join(d, 'ap_invoices.csv'), 'w', encoding='utf-8').write(CORPUS._csv([CORPUS.GOOD]))
        fp = PK.fingerprint_of(FileImportConnector(d, {'ap_invoice': FileSpec('ap_invoices.csv')}))
    finally:
        shutil.rmtree(d)
    p = PK.build_pack(IID, DEF.by_entity(cfg['definitions']), ['ap_invoice'], [fp])
    cfg['packs'][p['pack_id']] = p
    return cfg, p


CFG, PACK = None, None


def _policy(case):
    return replace(D.DEMO_POLICY, limits=replace(mapping.Limits(), **case['limits'])) if case['limits'] else D.DEMO_POLICY


def run_auif(case):
    from auif_ext.connectors.file_import import FileImportConnector, FileSpec
    clock, prov, store, audit, who = world()
    s = who('t', 'zero_one', 'ann')
    d = tempfile.mkdtemp()
    try:
        open(os.path.join(d, 'ap_invoices.csv'), 'wb').write(case['data'])
        env = client.AuifEnvironment(HERE_ROOT, CFG)
        env.bind('zero_one', s, clock)
        conn = FileImportConnector(d, {'ap_invoice': FileSpec('ap_invoices.csv')}, connector_id=PK.CONNECTOR[0], version=PK.CONNECTOR[1])
        env.add_integration('zero_one', IID, conn, PACK, 'accounting', ['ap_invoice'], {'ap_invoice': env.entity_config('ap_invoice', policy=_policy(case), file_name='ap_invoices.csv')})
        env.start()
        env.activate('zero_one', IID)
        summary = env.import_entity('zero_one', IID, 'ap_invoice')
        return summary, records(s, 'ap_invoice'), gate.assessment_status(s, [(IID, 'ap_invoice')], env.module)
    finally:
        shutil.rmtree(d)


def run_m3(case, data=None):
    clock, prov, store, audit, who = world()
    s = who('t', 'zero_one', 'ann')
    try:
        rc = P.ingest_file(s, clock, TPL, data if data is not None else case['data'], 'accounting', case['id'] + '.csv', _policy(case))
    except TenantMismatch:
        rc = None
    st = gate.receipt_status({'f': rc} if rc else {}, ['f'])
    return rc, records(s, 'ap_invoice'), st


class TestCorpusDeclarationIsComplete(unittest.TestCase):
    def test_every_corpus_case_is_declared_exactly_once(self):
        ids = list(DECL['same']) + list(DECL['refused_on_both_paths']) + list(DECL['differs'])
        self.assertEqual(sorted(ids), sorted(CASES))
        self.assertEqual(len(ids), len(set(ids)))

    def test_the_m3_path_still_gives_the_corpus_answers(self):
        from apg.ingest import golden_m3 as GM
        for cid, c in CASES.items():
            clock, prov, store, audit, who = world()
            ok, msg = CORPUS.check_case(c, who('t', 'zero_one', 'ann'), clock, TPL, D.DEMO_POLICY, P.ingest_file, mapping.Limits, TenantMismatch)
            self.assertTrue(ok, (cid, msg))


class TestCorpusThroughAuif(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        global CFG, PACK
        CFG, PACK = _config()

    def test_same(self):
        for cid in DECL['same']:
            with self.subTest(cid):
                (s, recs, st), (rc, recs3, st3) = run_auif(CASES[cid]), run_m3(CASES[cid])
                self.assertEqual({k: comparable(v) for k, v in recs.items()}, {k: comparable(v) for k, v in recs3.items()})
                self.assertEqual((st['status'], codes(st)), (st3['status'], codes(st3)))
                if rc and rc.get('status') == 'ingested':
                    self.assertIn(s['status'], ('applied',))
                    self.assertEqual((s['receipt']['counts'], s['receipt']['results']), (rc['counts'], rc['results']))

    def test_refused_on_both_paths(self):
        for cid in DECL['refused_on_both_paths']:
            with self.subTest(cid):
                (s, recs, st), (rc, recs3, st3) = run_auif(CASES[cid]), run_m3(CASES[cid])
                self.assertTrue(rc is None or rc['status'] == 'file_rejected', rc)
                self.assertEqual((recs, recs3), ({}, {}))
                self.assertEqual(s['status'], 'blocked')
                self.assertEqual((st['status'], st3['status']), ('cannot_assess', 'cannot_assess'))

    def test_differs_as_declared(self):
        for cid, why in DECL['differs'].items():
            with self.subTest(cid):
                s, recs, st = run_auif(CASES[cid])
                if cid == 'F09':                                        # the byte-order mark is dropped: the same as the good file on the M3 path
                    _, good, gst = run_m3(CASES[cid], CASES[cid]['data'].decode('utf-8-sig').encode('utf-8'))
                    self.assertEqual({k: comparable(v) for k, v in recs.items()}, {k: comparable(v) for k, v in good.items()})
                    self.assertEqual((st['status'], gst['status']), ('can_assess', 'can_assess'))
                else:
                    self.assertEqual(recs, {})
                    self.assertEqual(s['status'], 'blocked')
                    self.assertEqual(st['status'], 'cannot_assess')
                    rc, recs3, st3 = run_m3(CASES[cid])
                    self.assertTrue(recs3 or cid == 'T01' or rc)                # M3 stores the good row (or, for T01, strips the column and stores it; for F11, records an empty receipt)
                    self.assertEqual(st3['status'], 'can_assess' if cid in ('T01', 'H10', 'F11') else 'cannot_assess')   # M3 rejects a row in R01-R03 and R13; it skips blank lines (H10); M8-R1: it records an empty delivery (F11)


if __name__ == '__main__':
    unittest.main()
